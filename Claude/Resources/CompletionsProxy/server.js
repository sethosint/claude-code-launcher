function generateMachineId() {
  const invalidMacs = new Set(["00:00:00:00:00:00", "ff:ff:ff:ff:ff:ff", "ac:de:48:00:11:22"]);
  const ifaces = os.networkInterfaces();
  for (const name in ifaces) {
    for (const { mac } of ifaces[name]) {
      if (!invalidMacs.has(mac)) {
        return crypto.createHash("sha256").update(mac, "utf8").digest("hex");
      }
    }
  }
  return crypto.randomUUID().replace(/-/g, "").padEnd(64, "0");
}
