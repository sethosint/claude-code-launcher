/**
 * completions-proxy v1.1 — Claude Code via Completions
 *
 * HOW IT WORKS:
 *   1. Claude Code sends Anthropic Messages API requests to this proxy
 *   2. Proxy converts them to OpenAI Chat Completions format (including tools)
 *   3. Routes through Completions /api/v1/chat/completions endpoint
 *   4. Completions server forwards to GitHub Copilot with proper auth
 *   5. Converts OpenAI streaming response back to Anthropic SSE format
 *   6. Claude Code receives proper tool_use blocks and works normally
 *
 * RESULT: Full Claude Code functionality (tools, file ops, bash, streaming)
 *         through your free Completions API key.
 */

// ── Survive the launcher closing ────────────────────────────────────────────
// ClaudeLauncher starts this proxy with redirected stdio and (with "Close
// after launch" enabled) exits a moment later. That closes the read end of
// our stdout/stderr pipes, so the very next log line raises EPIPE — which,
// unhandled, killed the proxy while Claude Code was still using it. Swallow
// exactly those errors and keep serving.
function ignoreBrokenPipe(error) {
  return !!error && (error.code === "EPIPE" || error.code === "ERR_STREAM_DESTROYED");
}
process.stdout.on("error", (error) => { if (!ignoreBrokenPipe(error)) throw error; });
process.stderr.on("error", (error) => { if (!ignoreBrokenPipe(error)) throw error; });
process.on("uncaughtException", (error) => {
  if (ignoreBrokenPipe(error)) return;
  try { process.stderr.write(`\nFatal: ${error && error.stack ? error.stack : error}\n`); } catch {}
  process.exit(1);
});

