function resolveModel(requestedModel) {
  if (FORCE_MODEL) return FORCE_MODEL;
  if (!requestedModel || typeof requestedModel !== "string") return DEFAULT_MODEL;
  const mapped = MODEL_MAP[requestedModel];
  if (mapped) return mapped;
  const stripped = requestedModel.replace(/-\d{8,}$/, "");
  if (MODEL_MAP[stripped]) return MODEL_MAP[stripped];
  const dotted = stripped.replace(/(\d)-(\d)/g, "$1.$2");
  if (MODEL_MAP[dotted]) return MODEL_MAP[dotted];
  return requestedModel;
}

function getModelMaxOutput(modelId) {
  const found = SUPPORTED_MODELS.find(m => m.id === modelId);
  return found ? found.max_output_tokens : 16384;
}

function convertSystem(system) {
  if (!system) return null;
  if (typeof system === "string") return system;
  if (Array.isArray(system)) {
    return system.filter(b => b.type === "text").map(b => b.text).join("\n\n");
  }
  return null;
}

function convertAnthropicMessages(messages) {
  const result = [];
  for (const msg of messages) {
    if (msg.role === "assistant") {
      const textParts = [];
      const toolCalls = [];
      if (typeof msg.content === "string") {
        textParts.push(msg.content);
      } else if (Array.isArray(msg.content)) {
        for (const block of msg.content) {
          if (block.type === "text") textParts.push(block.text);
          else if (block.type === "tool_use") {
            toolCalls.push({
              id: block.id, type: "function",
              function: { name: block.name, arguments: typeof block.input === "string" ? block.input : JSON.stringify(block.input) },
            });
          }
        }
      }
      const assistantMsg = { role: "assistant", content: textParts.join("") || null };
      if (toolCalls.length > 0) assistantMsg.tool_calls = toolCalls;
      result.push(assistantMsg);
    } else if (msg.role === "user") {
      if (typeof msg.content === "string") {
        result.push({ role: "user", content: msg.content });
      } else if (Array.isArray(msg.content)) {
        const toolResults = [];
        const contentParts = [];
        for (const block of msg.content) {
          if (block.type === "tool_result") {
            let content = "";
            if (typeof block.content === "string") content = block.content;
            else if (Array.isArray(block.content)) content = block.content.filter(c => c.type === "text").map(c => c.text).join("\n");
            if (block.is_error) content = `[ERROR] ${content}`;
            toolResults.push({ role: "tool", tool_call_id: block.tool_use_id, content: content || "" });
          } else if (block.type === "text") {
            contentParts.push({ type: "text", text: block.text });
          } else if (block.type === "image") {
            if (block.source?.type === "base64") {
              contentParts.push({ type: "image_url", image_url: { url: `data:${block.source.media_type};base64,${block.source.data}` } });
            }
          }
        }
        for (const tr of toolResults) result.push(tr);
        if (contentParts.length === 1 && contentParts[0].type === "text") result.push({ role: "user", content: contentParts[0].text });
        else if (contentParts.length > 0) result.push({ role: "user", content: contentParts });
      }
    }
  }
  return result;
}

function convertAnthropicTools(tools) {
  if (!tools || !Array.isArray(tools) || tools.length === 0) return undefined;
  return tools.map(t => ({
    type: "function",
    function: { name: t.name, description: t.description || "", parameters: t.input_schema || { type: "object", properties: {} } },
  }));
}

function convertToolChoice(toolChoice) {
  if (!toolChoice) return undefined;
  if (typeof toolChoice === "string") return toolChoice;
  if (toolChoice.type === "auto") return "auto";
  if (toolChoice.type === "any") return "required";
  if (toolChoice.type === "tool" && toolChoice.name) return { type: "function", function: { name: toolChoice.name } };
  return undefined;
}

function buildChatRequest(body, model) {
  const messages = [];
  const systemText = convertSystem(body.system);
  if (systemText) messages.push({ role: "system", content: systemText });
  messages.push(...convertAnthropicMessages(body.messages || []));
  const req = {
    model, messages,
    max_tokens: body.max_tokens || getModelMaxOutput(model),
    temperature: body.temperature ?? 1,
    top_p: body.top_p ?? 1,
    n: 1, stream: body.stream !== false,
  };
  const tools = convertAnthropicTools(body.tools);
  if (tools) {
    req.tools = tools;
    const choice = convertToolChoice(body.tool_choice);
    if (choice) req.tool_choice = choice;
  }
  if (body.stop_sequences && body.stop_sequences.length > 0) req.stop = body.stop_sequences;
  return req;
}

