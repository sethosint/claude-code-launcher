function preConfigureClaude() {
  const home = process.env.HOME || process.env.USERPROFILE || ".";
  const configPath = path.join(home, ".claude.json");
  try {
    let config = {};
    if (fs.existsSync(configPath)) { try { config = JSON.parse(fs.readFileSync(configPath, "utf8")); } catch {} }
    config.hasCompletedOnboarding = true;
    config.completedOnboardingAt = config.completedOnboardingAt || new Date().toISOString();
    config.hasSeenWelcome = true;
    config.selectedTheme = config.selectedTheme || "dark";
    config.bypassPermissionsAccepted = true;
    config.bypassPermissionsAcceptedAt = config.bypassPermissionsAcceptedAt || new Date().toISOString();
    const proxyKey = CLIENT_KEY;
    if (!config.customApiKeyResponses) config.customApiKeyResponses = { approved: [], rejected: [] };
    if (!config.customApiKeyResponses.approved) config.customApiKeyResponses.approved = [];
    // Claude Code has used different shapes over time (the raw key, its last
    // 20 characters, its first 20 padded). Approving all of them keeps the
    // launch non-interactive whichever version is installed.
    const keyVariants = [
      proxyKey,
      proxyKey.slice(-20),
      proxyKey.slice(0, 20).padEnd(20, "x"),
    ];
    for (const variant of keyVariants) {
      if (!config.customApiKeyResponses.approved.includes(variant)) config.customApiKeyResponses.approved.push(variant);
    }
    const cwd = process.cwd();
    if (!config.trustedWorkspaces) config.trustedWorkspaces = [];
    if (!config.trustedWorkspaces.includes(cwd)) config.trustedWorkspaces.push(cwd);
    fs.writeFileSync(configPath, JSON.stringify(config, null, 2), "utf8");
    log("info", `Pre-configured Claude Code settings`);
  } catch (e) {
    log("info", `Could not pre-configure Claude: ${e.message}`);
  }
}

function launchClaude() {
  // Even when the proxy is not the one launching Claude Code (the GUI
  // launcher does it), Claude still needs its onboarding/API-key prompts
  // pre-answered — otherwise it stops at an interactive question the user
  // never sees in a freshly spawned terminal.
  preConfigureClaude();
  if (!AUTO_LAUNCH) return;

  let claudeBin = null;
  if (process.platform === "win32") {
    try { execSync("where claude", { stdio: "ignore" }); claudeBin = "claude"; } catch {}
    if (!claudeBin) {
      const npmGlobal = process.env.APPDATA ? path.join(process.env.APPDATA, "npm", "claude.cmd") : null;
      if (npmGlobal) try { fs.accessSync(npmGlobal); claudeBin = npmGlobal; } catch {}
    }
  } else {
    try { execSync("which claude", { stdio: "ignore" }); claudeBin = "claude"; } catch {}
    if (!claudeBin) {
      const candidates = [
        path.join(process.env.HOME || "", ".npm-global", "bin", "claude"),
        path.join(process.env.HOME || "", ".local", "bin", "claude"),
        "/usr/local/bin/claude",
        path.join(process.env.HOME || "", ".nix-profile", "bin", "claude"),
        path.join(process.env.HOME || "", ".local", "state", "nix", "profile", "bin", "claude"),
      ];
      try {
        const npmRoot = execSync("npm root -g", { encoding: "utf8", timeout: 5000, stdio: ["pipe", "pipe", "ignore"] }).trim();
        if (npmRoot) { const npmBin = path.resolve(npmRoot, "..", "bin"); candidates.unshift(path.join(npmBin, "claude")); }
      } catch {}
      for (const c of candidates) { try { fs.accessSync(c, fs.constants.X_OK); claudeBin = c; break; } catch {} }
    }
  }

  if (!claudeBin) {
    console.log(`  ${C.yellow}Claude Code not found in PATH.${C.reset}`);
    console.log(`  ${C.dim}Install: npm install -g @anthropic-ai/claude-code${C.reset}`);
    console.log(`  ${C.dim}Then re-run, or launch manually:${C.reset}`);
    console.log(`  ${C.dim}  ANTHROPIC_BASE_URL=http://localhost:${activePort} ANTHROPIC_API_KEY=copilot-proxy claude --model ${DEFAULT_MODEL}${C.reset}\n`);
    return;
  }

  let patchedCliPath = null;
  try {
    patchClaudeModelPicker(false);
    const home = process.env.HOME || process.env.USERPROFILE || ".";
    let wrapperPath;
    if (process.platform === "win32") {
      wrapperPath = path.join(process.env.APPDATA || home, "copilot-claude-proxy", "bin", "claude-patched.cmd");
    } else {
      wrapperPath = path.join(home, ".local", "bin", "claude-patched");
    }
    if (fs.existsSync(wrapperPath)) {
      patchedCliPath = wrapperPath;
      console.log(`  ${C.green}Using patched Claude binary for custom model picker${C.reset}`);
    }
  } catch (e) { console.log(`  ${C.dim}[patch] Failed: ${e.message}${C.reset}`); }

  const workDir = CLAUDE_CWD && fs.existsSync(CLAUDE_CWD) ? path.resolve(CLAUDE_CWD) : process.cwd();
  console.log(`  ${C.green}Launching Claude Code in ${C.cyan}${workDir}${C.reset}`);
  console.log(`  ${C.dim}Logs → ${LOG_FILE}${C.reset}`);
  console.log();
  console.log(`  ${C.yellow}Custom models — use /model <id> inside Claude Code:${C.reset}`);
  const vendors = {};
  for (const m of SUPPORTED_MODELS) { if (!vendors[m.vendor]) vendors[m.vendor] = []; vendors[m.vendor].push(m.id); }
  for (const [vendor, ids] of Object.entries(vendors)) console.log(`  ${C.dim}  ${vendor}: ${ids.join(", ")}${C.reset}`);
  console.log();
  console.log(`  ${C.cyan}To launch from another terminal:${C.reset}`);
  console.log(`  ${C.green}  completions${C.reset}                  ${C.dim}# from any directory${C.reset}`);
  console.log(`  ${C.green}  completions /path/to/project${C.reset}  ${C.dim}# specific directory${C.reset}`);
  console.log();
  console.log(`  ${C.dim}Or manually:${C.reset}`);
  if (process.platform === "win32") {
    console.log(`  ${C.dim}  $env:ANTHROPIC_BASE_URL="http://localhost:${activePort}"; $env:ANTHROPIC_API_KEY="copilot-proxy"; claude --model ${DEFAULT_MODEL}${C.reset}`);
  } else {
    console.log(`  ${C.dim}  ANTHROPIC_BASE_URL=http://localhost:${activePort} ANTHROPIC_API_KEY=copilot-proxy claude --model ${DEFAULT_MODEL}${C.reset}`);
  }
  console.log();

  silentMode = true;

  const env = {
    ...process.env,
    ANTHROPIC_BASE_URL: `http://localhost:${activePort}`,
    ANTHROPIC_API_URL: `http://localhost:${activePort}`,
    ANTHROPIC_API_KEY: "copilot-proxy",
    DISABLE_AUTOUPDATER: "1",
  };
  delete env.ANTHROPIC_AUTH_TOKEN;

  const launchBin = patchedCliPath || claudeBin;
  const child = spawn(launchBin, ["--model", DEFAULT_MODEL], { env, stdio: "inherit", shell: true, cwd: workDir });
  child.on("exit", (code) => {
    silentMode = false;
    console.log(`\n  ${C.dim}Claude Code exited (${code}). Proxy still running — Ctrl+C to stop.${C.reset}`);
  });
}

// ── Graceful Shutdown ───────────────────────────────────────────────────────

let server;

async function listenWithFallback(preferredPort, maxAttempts = 25) {
  if (PORT_STRICT) maxAttempts = 1;
  for (let attempt = 0; attempt < maxAttempts; attempt++) {
    const candidatePort = preferredPort + attempt;
    const started = await new Promise((resolve, reject) => {
      const instance = app.listen(candidatePort);
      instance.once("listening", () => resolve(instance));
      instance.once("error", (err) => {
        instance.close(() => { if (err && err.code === "EADDRINUSE") resolve(null); else reject(err); });
      });
    });
    if (started) {
      if (attempt > 0) log("info", `${C.yellow}Port ${preferredPort} busy${C.reset} → using ${C.green}${candidatePort}${C.reset}`);
      activePort = candidatePort;
      return started;
    }
  }
  if (PORT_STRICT) {
    throw new Error(
      `Port ${preferredPort} is already in use by another process. ` +
      `Close that process, or change "CompletionsGateway.BaseUrl" in the launcher config.json.`);
  }
  throw new Error(`No free port found in range ${preferredPort}-${preferredPort + maxAttempts - 1}`);
}

function shutdown(signal) {
  console.log(`\n${C.yellow}[shutdown]${C.reset} ${signal} received — closing server…`);
  if (server) server.close(() => {
    console.log(`${C.green}[shutdown]${C.reset} Server closed. ${requestCount} requests served, ${totalChars} chars generated.`);
    process.exit(0);
  });
  setTimeout(() => process.exit(0), 3000);
}
process.on("SIGINT", () => shutdown("SIGINT"));
process.on("SIGTERM", () => shutdown("SIGTERM"));

// ── Startup ─────────────────────────────────────────────────────────────────

async function main() {
  console.log(`\n  ${C.cyan}Completions Proxy v1.0${C.reset} — ${C.green}${DEFAULT_MODEL}${C.reset}\n`);

  // Load or prompt for API key
  if (process.env.COMPLETIONS_API_KEY) {
    apiKey = process.env.COMPLETIONS_API_KEY;
    log("auth", `Using COMPLETIONS_API_KEY env var: ${apiKey.slice(0, 12)}…`);
  } else {
    const config = loadConfig();
    if (config?.apiKey) {
      apiKey = config.apiKey;
      log("auth", `Loaded API key from config: ${apiKey.slice(0, 12)}…`);
    } else {
      apiKey = await promptApiKey(COPILOT_SAAS_URL);
      saveConfig({ apiKey, saasUrl: COPILOT_SAAS_URL });
      log("auth", "API key saved to config");
    }
  }

  // Validate the key
  try {
    const res = await fetch(`${COPILOT_SAAS_URL}/api/v1/models`, {
      headers: { authorization: `Bearer ${apiKey}` },
    });
    if (res.ok) {
      log("auth", `${C.green}API key validated${C.reset}`);
    } else {
      log("auth", `${C.yellow}WARNING: API key validation failed (${res.status})${C.reset}`);
    }
  } catch (e) {
    log("auth", `${C.yellow}WARNING: Could not reach ${COPILOT_SAAS_URL}: ${e.message}${C.reset}`);
  }

  startTime = Date.now();
  server = await listenWithFallback(BASE_PORT);
  console.log(`  ${C.green}✓${C.reset} Proxy on ${C.cyan}http://localhost:${activePort}${C.reset}`);

  launchClaude();
}

main().catch((e) => {
  console.error(`\n${C.red}Fatal: ${e.message}${C.reset}`);
  process.exit(1);
});
