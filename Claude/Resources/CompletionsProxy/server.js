function openAiResponsesInputToMessages(input) {
  if (typeof input === "string") return [{ role: "user", content: input }];
  if (!Array.isArray(input)) return [{ role: "user", content: "" }];
  const texts = [];
  for (const item of input) {
    if (!item) continue;
    if (typeof item === "string") { texts.push(item); continue; }
    if (item.type === "input_text" && typeof item.text === "string") { texts.push(item.text); continue; }
    if (item.type === "message") {
      if (typeof item.content === "string") texts.push(item.content);
      else if (Array.isArray(item.content)) { for (const block of item.content) { if (block && typeof block.text === "string") texts.push(block.text); } }
    }
  }
  return [{ role: "user", content: texts.join("\n\n") }];
}

